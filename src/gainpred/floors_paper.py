"""Files for the paper from the pilot (protocol amendment 27, part 4). New files only.

Writes, into ``paper/generated/`` (never touching an existing file there):

* ``numbers_pilot.tex``: one macro per number in the tables and figure below and in the
  control's result, all named ``\\gpClimb...`` (not added to ``numbers.tex``); and
  ``results/pilot/macros.md``, which lists each macro, its value and what it means;
* ``table_climb.tex``, ``table_climb_control.tex``, ``table_climb_weak.tex``,
  ``table_climb_skip.tex``, ``table_climb_rule.tex``, ``table_climb_splits.tex``;
* ``figure_climb_errors.pdf`` and ``figure_climb_errors.tex``.

How the numbers are kept in step
================================
Every number that goes into a table passes through ``Reg.add``, which returns its printed form and
records a macro for it. So a cell and its macro are the same string, made once, from the logs.
Macro names may hold letters only, so digits are spelled out (16 -> ``Sixteen``).

Run: ``uv run python -m gainpred.floors_paper``.
"""

