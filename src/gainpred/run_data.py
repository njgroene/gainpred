"""Longest-run datasets (experiment 2): easy strings, hard problems, test sets, starting training.

Run ``uv run python -m gainpred.run_data`` to write them to ``data/longest_run/``.
As for addition (``gainpred.data``), the files are not in git: they are
regenerated byte for byte from the seeds below, and ``manifest.json`` records
each file's seed, size and SHA-256 fingerprint.

Easy strings (P1)
=================
An easy string has 6-10 symbols, each a digit 0-9. Shin et al. (A.1.3) say
only "a string x over the digits 0-9"; they do not say how the digits are
drawn. **Assumption (P10):** each symbol is drawn uniformly and independently.
Two numbers in their paper support this. Under uniform digits, the edges of
two joined strings are equal one time in ten, so their filter should keep 90%
of parents -- their Table 7 reports "kept 90.0". And with strings of length
11-83 cut into ceil(L/10) blocks, the share of strings with no run crossing a
block boundary comes out at about 66%, against their 66.2% (Section C.7; the
paper test, ``gainpred.run_paper_test``, recomputes this).

Unlike addition, a string may start with 0: it is a string, not a number.

Hard problems (P3, P6)
======================
A hard string is two easy strings joined: lengths 12-20, each piece 6-10.
The place where the two pieces meet is the **join** (P4: "one cut at the
join"). Two kinds, half each (P6)::

    random join     "493036" + "887476"       -> "493036887476"   join 6
    run across      left  "4930 36"  a = 2 symbols set to 7 -> "493077"
    the join        right "88 7476"  b = 2 symbols set to 7 -> "777476"
                    joined: "493077777476": a run of four 7s across the join

In a run across the join, the last *a* symbols of the left piece and the
first *b* of the right are set to one symbol, *a* and *b* each 1-4, and the
symbols just outside that stretch must differ from it, so the run across the
join has length exactly *a* + *b* (2-8). These are the problems where Shin et
al.'s "pick the longer" can go wrong (``gainpred.run_teachers``).

The **withheld** version of experiment 2 (P6) discards run-across-the-join
problems with *a* of 3 or 4 (``withheld``): the model then never trains on a
problem whose run sticks 3 or more symbols out of the left piece, and the test
set asks whether it can answer them anyway. All versions draw from the same
fixed pool; the withheld version filters it.

What gets generated, in this order (P7)
=======================================
1. **Test sets first, each from its own seed.**

   ==========  ===============================================================
   test_study  hard strings, 1,000 per group: random joins; run across the
               join by joined run length a + b = 2..8; run across the join
               by left part a = 1-2 versus a = 3-4 (10 groups in all)
   test_easy   the three questions (runlen, leftrun, rightrun) at lengths
               6-10, 1,000 per question type and length; each row records
               the run length of its answer, so check 0 can be reported by
               run length (P7, P8)
   ==========  ===============================================================

2. **Starting training** (P1): 50,000 strings per length 6-10, none of them a
   test string. P3 leaves open how the edge-run questions enter it; the
   default it states is used here -- every string is asked all three
   questions -- but it is a parameter (``TRAIN_START_QUESTIONS``).

Strings are unique within and across all sets ("excluded" is by string: a
string used in a test set is never used in training, whatever the question).

Reproducibility
===============
As in ``gainpred.data``: every random choice is derived from
``random.Random.random()`` only, which Python keeps stable across versions,
and the tests freeze the file fingerprints.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import random
from collections.abc import Callable, Iterable
from dataclasses import dataclass
from pathlib import Path

from gainpred.data import _digit, load, to_jsonl  # noqa: F401  (load: reading .jsonl is the same for both tasks)
from gainpred.formats import RUN_QUESTIONS, Run, RunQuestion, run_answer_text, runs

# ----------------------------------------------------------------------------
# Settings. Changing any of these changes the datasets: record it in P10.
# ----------------------------------------------------------------------------
SEEDS = {
    "test_study": 1_101,
    "test_easy": 1_102,
    "train_start": 2_101,
}
"""One fixed seed per set. Chosen not to clash with addition's seeds (1001-1003,
2001, 3001, and 7,000,000+ for rounds)."""

EASY_LENGTHS = range(6, 11)  # P1: lengths 6-10
HARD_LENGTHS = range(12, 21)  # P3: lengths 12-20, two pieces of 6-10
EDGE_PART = range(1, 5)  # P6: a and b each drawn from 1 to 4
WITHHELD_A = frozenset({3, 4})  # P6: the withheld version drops run-across problems with these a

RUN_ACROSS_SHARE = 0.5  # P6: half random join, half run across the join

TEST_STUDY_PER_GROUP = 1_000  # P7
TEST_EASY_PER_GROUP = 1_000  # P7: per question type and length
TRAIN_START_PER_LENGTH = 50_000  # P1
TRAIN_START_QUESTIONS: tuple[str, ...] = RUN_QUESTIONS
"""Which questions each starting-training string is asked. P3's stated default:
all three. Set to ("runlen",) to train as Shin et al. did (P10 departure)."""

JOINED_LENGTHS = range(2, 9)  # P7: run-across-the-join groups by a + b = 2..8
LEFT_PARTS = {"1-2": (1, 2), "3-4": (3, 4)}  # P7: groups by left part a

DEFAULT_OUT_DIR = Path("data/longest_run")

RANDOM_JOIN = "random_join"
RUN_ACROSS = "run_across"

Record = dict[str, int | str | None]


# ----------------------------------------------------------------------------
# Hard problems as objects
# ----------------------------------------------------------------------------


@dataclass(frozen=True)
class HardRun:
    """A hard longest-run problem: a string joined from two easy pieces (P6).

    ``join`` is the length of the left piece, so the pieces are
    ``string[:join]`` and ``string[join:]``. ``kind`` is ``"random_join"`` or
    ``"run_across"``; for a run across the join, ``a`` and ``b`` are how many
    symbols of the left and right piece were set to the shared symbol (None
    for a random join). The question asked is always ``runlen(string)``.
    """

    string: str
    join: int
    kind: str
    a: int | None = None
    b: int | None = None

    def __post_init__(self) -> None:
        if not 0 < self.join < len(self.string):
            raise ValueError(f"join {self.join} is not inside a string of length {len(self.string)}")
        if self.kind not in (RANDOM_JOIN, RUN_ACROSS):
            raise ValueError(f"unknown kind {self.kind!r}")
        if (self.kind == RUN_ACROSS) != (self.a is not None and self.b is not None):
            raise ValueError("a and b are given exactly for run-across-the-join problems")

    @property
    def left(self) -> str:
        return self.string[: self.join]

    @property
    def right(self) -> str:
        return self.string[self.join :]

    @property
    def length(self) -> int:
        return len(self.string)

    @property
    def question(self) -> RunQuestion:
        """What the model is asked directly: ``runlen`` of the whole string."""
        return RunQuestion("runlen", self.string)

    @property
    def joined_length(self) -> int | None:
        """Length of the planted run across the join, a + b (None for a random join)."""
        return None if self.a is None or self.b is None else self.a + self.b


def withheld(problems: Iterable[HardRun]) -> list[HardRun]:
    """P6, the withheld version: drop run-across-the-join problems with a of 3 or 4.

    Random joins pass through unchanged, even when their edges happen to
    match: P6 discards by the construction parameter *a*, not by what the
    string turned out to contain.
    """
    return [p for p in problems if not (p.kind == RUN_ACROSS and p.a in WITHHELD_A)]


# ----------------------------------------------------------------------------
# Drawing
# ----------------------------------------------------------------------------


def _uniform(rng: random.Random, options: tuple | range | list):
    """A uniform choice using only rng.random() (stable across Python versions)."""
    return options[int(rng.random() * len(options))]


def draw_string(rng: random.Random, length: int) -> str:
    """An easy-style string: each symbol a uniform digit 0-9 (P10 assumption)."""
    return "".join(str(_digit(rng, nonzero=False)) for _ in range(length))


def _other_symbol(rng: random.Random, symbol: str) -> str:
    """A uniform digit different from ``symbol`` (one of the other nine)."""
    d = int(rng.random() * 9)
    return str(d + 1 if d >= int(symbol) else d)


def left_lengths(length: int) -> range:
    """Every left-piece length that leaves both pieces 6-10 (P3).

    12 -> 6 only; 16 -> 6..10; 20 -> 10 only.
    """
    low, high = min(EASY_LENGTHS), max(EASY_LENGTHS)
    return range(max(low, length - high), min(high, length - low) + 1)


def draw_join(rng: random.Random, length: int) -> int:
    """Where the pieces meet: uniform over the valid left lengths (P10 assumption)."""
    options = left_lengths(length)
    if not options:
        raise ValueError(f"length {length} cannot be made of two pieces of {EASY_LENGTHS}")
    return _uniform(rng, options)


def draw_random_join(rng: random.Random, length: int) -> HardRun:
    """P6, random join: two easy strings placed side by side."""
    join = draw_join(rng, length)
    return HardRun(draw_string(rng, join) + draw_string(rng, length - join), join, RANDOM_JOIN)


def draw_run_across(rng: random.Random, length: int, a: int | None = None, b: int | None = None) -> HardRun:
    """P6, run across the join, with *a* and *b* drawn from 1-4 unless given.

    Steps, for left "493036", right "887476", symbol 7, a = 2, b = 2::

        left  "4930" + "77"   (last a symbols set to 7)
        right "77" + "7476"   (first b symbols set to 7)
        "493077" + "777476": the symbols just outside the stretch, 0 and 4,
        already differ from 7. Had one been a 7, it would be redrawn
        uniformly from the other nine digits (P10 assumption: "must differ"
        is enforced by redrawing that one symbol, not the whole problem).

    The planted run therefore has length exactly a + b. Each piece is at
    least 6 long and a, b at most 4, so the outside symbols always exist.
    """
    join = draw_join(rng, length)
    left, right = draw_string(rng, join), draw_string(rng, length - join)
    a = a if a is not None else _uniform(rng, EDGE_PART)
    b = b if b is not None else _uniform(rng, EDGE_PART)
    symbol = str(_digit(rng, nonzero=False))
    outside_left, outside_right = left[-a - 1], right[b]
    if outside_left == symbol:
        outside_left = _other_symbol(rng, symbol)
    if outside_right == symbol:
        outside_right = _other_symbol(rng, symbol)
    left = left[: -a - 1] + outside_left + symbol * a
    right = symbol * b + outside_right + right[b + 1 :]
    return HardRun(left + right, join, RUN_ACROSS, a, b)


def draw_hard(rng: random.Random, length: int, run_across_share: float = RUN_ACROSS_SHARE) -> HardRun:
    """One hard problem of the training pool: run across the join with
    probability ``run_across_share`` (P6: half), else a random join.

    P10 assumption: "half" is a fair coin per problem, so a pool is half and
    half in expectation, not exactly.
    """
    if rng.random() < run_across_share:
        return draw_run_across(rng, length)
    return draw_random_join(rng, length)


def draw_pool(rng: random.Random, length: int, n: int, exclude: set[str]) -> list[HardRun]:
    """``n`` hard problems of one length with distinct strings, none in ``exclude``.

    This is "the one fixed pool" of P6: every version of experiment 2 draws
    from it with the same seed, and the withheld version applies ``withheld``
    afterwards. Pass the test strings in ``exclude`` (P7); it grows as we go.
    """
    chosen: list[HardRun] = []
    for _ in range(100 * n):
        if len(chosen) == n:
            break
        problem = draw_hard(rng, length)
        if problem.string not in exclude:
            exclude.add(problem.string)
            chosen.append(problem)
    if len(chosen) < n:
        raise RuntimeError(f"could only draw {len(chosen)} of {n} distinct hard strings")
    return chosen


# ----------------------------------------------------------------------------
# Records
# ----------------------------------------------------------------------------


def answers_of(string: str) -> dict[str, Run]:
    """All three answers of a string at once (finding the runs once is cheaper)."""
    all_runs = runs(string)
    return {"runlen": max(all_runs, key=lambda r: r.length), "leftrun": all_runs[0], "rightrun": all_runs[-1]}


def easy_record(kind: str, string: str, answer: Run) -> Record:
    """One easy row, e.g. {"question": "runlen", "string": "887476", "answer": "8|2", "length": 6, "run_length": 2}."""
    return {"question": kind, "string": string, "answer": run_answer_text(answer), "length": len(string),
            "run_length": answer.length}


def hard_record(problem: HardRun, group: str) -> Record:
    answer = answers_of(problem.string)["runlen"]
    return {"string": problem.string, "answer": run_answer_text(answer), "length": problem.length,
            "run_length": answer.length, "join": problem.join, "kind": problem.kind, "a": problem.a,
            "b": problem.b, "group": group}


def questions_of(records: list[Record]) -> list[RunQuestion]:
    """Easy records back into questions."""
    return [RunQuestion(str(r["question"]), str(r["string"])) for r in records]


def hard_problems_of(records: list[Record]) -> list[HardRun]:
    """Study-test records back into hard problems."""
    return [HardRun(str(r["string"]), int(r["join"]), str(r["kind"]), r["a"], r["b"]) for r in records]  # type: ignore[arg-type]


# ----------------------------------------------------------------------------
# Sets
# ----------------------------------------------------------------------------


def study_groups() -> dict[str, Callable[[random.Random], HardRun]]:
    """The ten study groups of P7 and how to draw one problem of each.

    Each problem's length is drawn uniformly from 12-20 (P10 assumption: P7
    does not say how the 1,000 per group spread over lengths). Within a
    joined-length group, (a, b) is uniform over the pairs with that sum;
    within a left-part group, a is uniform over its two values and b over 1-4.
    """
    def random_join(rng):
        return draw_random_join(rng, _uniform(rng, HARD_LENGTHS))

    def joined(total):
        pairs = [(a, total - a) for a in EDGE_PART if total - a in EDGE_PART]
        def draw(rng):
            length = _uniform(rng, HARD_LENGTHS)
            a, b = _uniform(rng, pairs)
            return draw_run_across(rng, length, a, b)
        return draw

    def left_part(values):
        def draw(rng):
            length = _uniform(rng, HARD_LENGTHS)
            return draw_run_across(rng, length, _uniform(rng, values), _uniform(rng, EDGE_PART))
        return draw

    groups = {RANDOM_JOIN: random_join}
    groups |= {f"joined_length_{t}": joined(t) for t in JOINED_LENGTHS}
    groups |= {f"left_part_{name}": left_part(values) for name, values in LEFT_PARTS.items()}
    return groups


def make_test_study(exclude: set[str], per_group: int = TEST_STUDY_PER_GROUP) -> list[Record]:
    """P7, longest run study set: 1,000 distinct hard strings per group.

    The groups are drawn separately (a problem belongs to exactly one group),
    so the left-part groups are not a re-slicing of the joined-length groups.
    Every record carries a and b, so either split can also be made within
    the other.
    """
    rng = random.Random(SEEDS["test_study"])
    records = []
    for group, draw in study_groups().items():
        count = 0
        while count < per_group:
            problem = draw(rng)
            if problem.string not in exclude:
                exclude.add(problem.string)
                records.append(hard_record(problem, group))
                count += 1
    return records


def _unique_strings(rng: random.Random, length: int, n: int, exclude: set[str]) -> list[str]:
    chosen: list[str] = []
    for _ in range(100 * n):
        if len(chosen) == n:
            break
        string = draw_string(rng, length)
        if string not in exclude:
            exclude.add(string)
            chosen.append(string)
    if len(chosen) < n:
        raise RuntimeError(f"could only draw {len(chosen)} of {n} distinct strings of length {length}")
    return chosen


def make_test_easy(exclude: set[str], per_group: int = TEST_EASY_PER_GROUP) -> list[Record]:
    """P7, easy problems for check 0: each question type at each length 6-10.

    Each (question, length) group has its own 1,000 strings, so no string is
    asked two questions in the test set.
    """
    rng = random.Random(SEEDS["test_easy"])
    records = []
    for kind in RUN_QUESTIONS:
        for length in EASY_LENGTHS:
            for string in _unique_strings(rng, length, per_group, exclude):
                records.append(easy_record(kind, string, answers_of(string)[kind]))
    return records


def make_train_start(
    exclude: set[str], per_length: int = TRAIN_START_PER_LENGTH, questions: tuple[str, ...] = TRAIN_START_QUESTIONS
) -> list[Record]:
    """P1 starting training: ``per_length`` strings per length 6-10, each asked ``questions``.

    With the default (all three questions, P3) that is 3 x 250,000 = 750,000
    rows. Rows of one string sit next to each other; training shuffles anyway.
    """
    rng = random.Random(SEEDS["train_start"])
    records = []
    for length in EASY_LENGTHS:
        for string in _unique_strings(rng, length, per_length, exclude):
            answers = answers_of(string)
            records += [easy_record(kind, string, answers[kind]) for kind in questions]
    return records


def make_all(train_start_questions: tuple[str, ...] = TRAIN_START_QUESTIONS) -> dict[str, list[Record]]:
    """Every longest-run set, in protocol order: test sets first, then training.

    One ``exclude`` set of strings is threaded through, so later sets avoid
    every string of earlier ones (P7).
    """
    exclude: set[str] = set()
    return {
        "test_study": make_test_study(exclude),
        "test_easy": make_test_easy(exclude),
        "train_start": make_train_start(exclude, questions=train_start_questions),
    }


# ----------------------------------------------------------------------------
# Files
# ----------------------------------------------------------------------------


def write_all(out_dir: Path = DEFAULT_OUT_DIR, train_start_questions: tuple[str, ...] = TRAIN_START_QUESTIONS) -> dict:
    """Generate every set, write ``<name>.jsonl`` files and ``manifest.json``."""
    out_dir.mkdir(parents=True, exist_ok=True)
    manifest = {}
    for name, records in make_all(train_start_questions).items():
        content = to_jsonl(records)
        (out_dir / f"{name}.jsonl").write_bytes(content)
        manifest[name] = {"seed": SEEDS[name], "rows": len(records), "sha256": hashlib.sha256(content).hexdigest()}
    manifest["train_start"]["questions"] = list(train_start_questions)
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate the longest-run datasets.")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT_DIR)
    args = parser.parse_args()
    manifest = write_all(args.out)
    for name, info in manifest.items():
        print(f"{name:<12} {info['rows']:>8,} rows   sha256 {info['sha256'][:16]}...")
    print(f"written to {args.out}/")


if __name__ == "__main__":
    main()
