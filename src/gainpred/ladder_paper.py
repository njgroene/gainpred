def config_of(seed: int, arm: int) -> dict:
    return json.loads((lr.RUNS / run_name(seed, arm) / "config-rounds1-main.json").read_text())["ladder"]


def one_setting(key: str, arms=ARMS, seeds=SEEDS):
    vals = {config_of(s, a).get(key) for s in seeds for a in arms}
    if len(vals) != 1:
        raise ValueError(f"setting {key} differs between arm runs: {vals}")
    return vals.pop()


