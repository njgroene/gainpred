def tex_escape(text: str) -> str:
    """LaTeX's special characters in plain text (the ones this module's text can hold)."""
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("_", r"\_"), ("#", r"\#"),
                 ("$", r"\$")):
        text = text.replace(a, b)
    return text


class LadReg(Reg):
    """``floors_paper.Reg`` with the prefix ``gpLad`` and the ladder's headers."""

    def add(self, parts: tuple, value: str, meaning: str) -> str:
        name = "gpLad" + macro_name(*parts)[len("gpClimb"):]
        if name in self.items and self.items[name][0] != value:
            raise ValueError(f"macro {name} given two values")
        self.items[name] = (value, meaning)
        return value

    def tex(self) -> str:
        lines = [NOTE, "% Numbers of the ladder (protocol amendments 29 and 30), seeds 5-7; read from",
                 "% results/ladder/runs/. Not part of numbers.tex."]
        lines += [rf"\newcommand{{\{k}}}{{{tex_escape(v)}}}" for k, (v, _) in self.items.items()]
        return "\n".join(lines) + "\n"

    def md(self) -> str:
        lines = ["# Macros for the paper: the ladder", "",
                 f"Generated by `{COMMAND}` into `paper/generated/numbers_ladder.tex`. Every value is read from the "
                 "logs in `results/ladder/runs/` (and the call files and configs there). Percentages have one "
                 "decimal unless the meaning says otherwise; differences are in percentage points.", "",
                 "| Macro | Value | Meaning |", "| --- | --- | --- |"]
        lines += [f"| `\\{k}` | {v} | {m} |" for k, (v, m) in self.items.items()]
        return "\n".join(lines) + "\n"


def p1(x: float) -> str:
    """A fraction as a percentage with one decimal."""
    return f1(100 * x)


def sign1(points: float) -> str:
    return f"{points:+.1f}"


# ---------------------------------------------------------------------------- reading one arm run

def run_name(seed: int, arm: int) -> str:
    return f"ladder_s{seed}_arm{arm}"


class Arm:
    """Everything this module reads from one arm run's ``rounds.jsonl``."""

    def __init__(self, seed: int, arm: int):
        self.seed, self.arm = seed, arm
        self.ev = lr.events(run_name(seed, arm))
        self.tests = lr.counting_tests(self.ev)
        self.first_tests = lr.first_attempt_tests(self.ev)
        self.redo_tests = {e["round"]: e["acc"] for e in lr.of(self.ev, "test") if e.get("redo")}
        self.checks = lr.of(self.ev, "check")
        self.builds = {(e["round"], e["digits"]): e for e in lr.of(self.ev, "build")}  # the last build counts
        self.skips = lr.of(self.ev, "skip_length")
        self.done = lr.of(self.ev, "round_done")
        self.diverged = lr.of(self.ev, "diverged")
        self.last_round = max(e["round"] for e in self.done)
        self.stages = lr.stages_of(self.ev)

    def acc(self, round_: int, d: int, key: str = "acc_total") -> float | None:
        return self.tests.get(round_, {}).get(str(d), {}).get(key)

    def final(self, d: int, key: str = "acc_total") -> float | None:
        return self.acc(self.last_round, d, key)

    def after_round(self, d: int, key: str = "acc_total") -> float | None:
        return self.acc((d - 6) // 2, d, key)

    def lowest_later(self, d: int, round_: int) -> float | None:
        vals = [a[str(d)]["acc_total"] for r, a in self.tests.items() if r > round_ and str(d) in a]
        return min(vals) if vals else None

    @property
    def stages_learned(self) -> int:
        return sum(1 for v in self.stages.values() if v)

    @property
    def last_length(self) -> int:
        return round_lengths(self.last_round)[1]

    def taught(self) -> range:
        return range(8, self.last_length + 1)

    def built_lengths(self) -> list[int]:
        return sorted({d for (_, d) in self.builds})

    def skipped_lengths(self) -> list[int]:
        return sorted({e["digits"] for e in self.skips})

    def trained_rounds(self) -> list[int]:
        return sorted({e["round"] for e in self.done if not e["round_skipped"]})

    def skipped_rounds(self) -> list[int]:
        return sorted({e["round"] for e in self.done if e["round_skipped"]})

    def logged_updates(self) -> int:
        """Sum of ``num_updates`` over every ``round_done`` (section 2's definition)."""
        return sum(e["num_updates"] for e in self.done)

    def attempts(self) -> list[dict]:
        """One dict per attempt of every round: {round, attempt, done, seconds_logged, test}.

        A round with two ``round_done`` events (a continuation's redo) gives one attempt per event.
        A ``round_done`` with ``redone`` and no ``continuation`` (a redo inside the call) gives two
        attempts from one event: the seconds are logged once, for both, and are put on attempt 1."""
        out = []
        by_round: dict[int, list[dict]] = {}
        for e in self.done:
            by_round.setdefault(e["round"], []).append(e)
        for r in sorted(by_round):
            evs = by_round[r]
            if len(evs) == 2:
                out.append(dict(round=r, attempt=1, done=evs[0], seconds=True, test=self.first_tests.get(r)))
                out.append(dict(round=r, attempt=2, done=evs[1], seconds=True, test=self.redo_tests.get(r)))
            elif len(evs) == 1 and evs[0].get("redone"):
                out.append(dict(round=r, attempt=1, done=evs[0], seconds=True, test=self.first_tests.get(r)))
                out.append(dict(round=r, attempt=2, done=evs[0], seconds=False, test=self.redo_tests.get(r)))
            elif len(evs) == 1:
                out.append(dict(round=r, attempt=None, done=evs[0], seconds=True, test=self.tests.get(r)))
            else:
                raise ValueError(f"{run_name(self.seed, self.arm)} round {r}: {len(evs)} round_done events")
        return out

    def updates_run(self) -> int:
        """Updates actually run: every attempt of a redone round counted."""
        return sum(a["done"]["num_updates"] for a in self.attempts() if not a["done"]["round_skipped"])

    def gpu_seconds(self) -> float:
        return sum(e[k] for e in self.done for k in lr.PARTS)


def load_arms() -> dict[tuple[int, int], Arm]:
    return {(s, a): Arm(s, a) for s in SEEDS for a in ARMS}


