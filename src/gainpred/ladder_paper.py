def write_all(paper: Path = PAPER, results: Path = LADDER_RESULTS) -> list[Path]:
    """Writes every output; returns the paths written."""
    arms = load_arms()
    got = section2(arms)
    if got != EXPECTED:
        raise SystemExit(f"section 2 values differ: computed {got}, expected {EXPECTED}")
    reg = build_register(arms)
    written = []
    texts = {"numbers_ladder.tex": reg.tex(), "table_ladder_lengths.tex": lengths_table(arms),
             "table_ladder_cuts.tex": cuts_table()}
    paper.mkdir(parents=True, exist_ok=True)
    for name, text in texts.items():
        (paper / name).write_text(wrap_text(text))
        written.append(paper / name)
    files = {"per_length.csv": csv_text(PER_LENGTH_COLUMNS, per_length_rows(arms)),
             "per_round.csv": csv_text(PER_ROUND_COLUMNS, per_round_rows(arms)), "macros.md": reg.md()}
    results.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (results / name).write_text(text)
        written.append(results / name)
    written += accuracy_figure(arms, paper, results)
    written += loss_figure(paper, results)
    written += decisions_figure(arms, paper, results)
    return written


