def section2(arms: dict[tuple[int, int], Arm]) -> dict[str, dict[int, str]]:
    """The values the task gives, computed here, as printed strings per seed."""
    out: dict[str, dict[int, str]] = {k: {} for k in (
        "skipped", "built", "trained", "updates4", "updates3", "low3", "low4", "diffmean", "arm1_8")}
    for s in SEEDS:
        a1, a3, a4 = arms[s, 1], arms[s, 3], arms[s, 4]
        out["skipped"][s] = str(len(a4.skipped_lengths()))
        out["built"][s] = str(len(a4.built_lengths()))
        out["trained"][s] = str(len(a4.trained_rounds()))
        out["updates4"][s] = f"{a4.logged_updates():,}"
        out["updates3"][s] = f"{a3.logged_updates():,}"
        out["low3"][s] = p1(min(a3.final(d) for d in LENGTHS))
        out["low4"][s] = p1(min(a4.final(d) for d in LENGTHS))
        out["diffmean"][s] = f"{statistics.mean(100 * (a4.final(d) - a3.final(d)) for d in LENGTHS):+.2f}"
        out["arm1_8"][s] = p1(a1.final(8))
    return out


