def tex_table(label: str, caption: str, spec: str, head: list[str], body: list[str], size: str) -> str:
    lines = [NOTE, r"\begin{table}[htbp]", r"\centering", rf"\caption{{{caption}}}", rf"\label{{tab:{label}}}",
             size, r"\setlength{\tabcolsep}{3pt}", rf"\begin{{tabular}}{{{spec}}}", r"\toprule", *head, r"\midrule",
             *body, r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def novelty_cell(x: float | None) -> str:
    if x is None:
        return "--"
    v = 100 * x
    return f"{v:.2f}" if v < 1 else f"{v:.1f}"


def lengths_table(arms) -> str:
    head = [" & " + " & ".join(rf"\multicolumn{{4}}{{c}}{{Seed {s}}}" for s in SEEDS) + r" \\",
            "".join(rf"\cmidrule(lr){{{2 + 4 * i}-{5 + 4 * i}}}" for i in range(3)),
            "Digits & " + " & ".join(["Agreed", "Paced", "Novelty", "Paced did"] * 3) + r" \\"]
    body = []
    for d in LENGTHS:
        if d in (16, 24, 32):
            body.append(r"\midrule")
        cells = [str(d)]
        for s in SEEDS:
            a3, a4 = arms[s, 3], arms[s, 4]
            c4 = next(c for c in a4.checks if c["digits"] == d)
            cells += [p1(a3.final(d)), p1(a4.final(d)), novelty_cell(c4["novelty_agreed"]),
                      "skipped" if d in a4.skipped_lengths() else "built"]
        body.append(" & ".join(cells) + r" \\")
    caption = tex_escape("For each length and seed: final accuracy (%) of the third arm (Agreed) and of the "
                         "self-paced arm (Paced) after their last round, the self-paced arm's novelty in its check "
                         "before the length's round (% of pair-agreed answers that differ from the direct answer), "
                         "and whether it built or skipped the length.")
    return tex_table("ladder-lengths", caption, "r" + "rrrl" * 3, head, body, r"\scriptsize")


def cuts_table() -> str:
    head = [r"\multicolumn{4}{c}{8--23 digits} & \multicolumn{4}{c}{24--39 digits} \\",
            r"\cmidrule(lr){1-4}\cmidrule(lr){5-8}",
            r"Digits & Split 1 & Split 2 & Split 3 & Digits & Split 1 & Split 2 & Split 3 \\"]
    body = []
    for i, d in enumerate(range(8, 24)):
        if i == 8:
            body.append(r"\midrule")
        cells = []
        for n in (d, d + 16):
            cells += [str(n)] + [f"{left} + {right}" for left, right in CUTS[n]]
        body.append(" & ".join(cells) + r" \\")
    caption = tex_escape("The three splits of every length 8-39, each written as left piece + right piece (digits).")
    caption = re.sub(r"(?<=\d)-(?=\d)", "--", caption)
    # The paper says "split" for the code's "cut" (tests/test_section4.py bans the old word in
    # every generated .tex line, a label included), so the label is tab:ladder-splits.
    return tex_table("ladder-splits", caption, "rlll@{\\hspace{1.5em}}rlll", head, body, r"\small")


