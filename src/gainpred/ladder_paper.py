def _cell(x) -> str:
    if x is None:
        return ""
    if isinstance(x, bool):
        return "1" if x else "0"
    return str(x)


def per_length_rows(arms: dict[tuple[int, int], Arm]) -> list[list]:
    rows = []
    for (s, a), arm in arms.items():
        for c in arm.checks:
            d, r = c["digits"], c["round"]
            b = arm.builds.get((r, d))
            prev = arm.tests.get(r - 1, {}).get(str(d))
            rows.append([s, a, d, r] + [c[k] for k in ("direct_acc", "cut1_acc", "confirmed_share", "agreed_share",
                                                        "m_agreed", "agreed_acc", "novelty_arm", "novelty_agreed",
                                                        "arm4_verdict")]
                        + [b is not None] + ([b[k] for k in ("sums_drawn", "answers_kept", "kept_acc",
                                                             "kept_carry_share")] if b else [None] * 4)
                        + [prev["acc_total"] if prev else None, arm.acc(r, d), arm.acc(r, d, "acc_carry"),
                           arm.acc(r, d, "acc_no_carry"), arm.final(d), arm.lowest_later(d, r)])
    return rows


def per_round_rows(arms: dict[tuple[int, int], Arm]) -> list[list]:
    rows = []
    for (s, a), arm in arms.items():
        div = {e["round"] for e in arm.diverged}
        for t in arm.attempts():
            e, r = t["done"], t["round"]
            built = sorted({d for (rr, d) in arm.builds if rr == r})
            skipped = sorted({x["digits"] for x in arm.skips if x["round"] == r})
            secs = [e[k] for k in (*lr.PARTS, "sec_total")] if t["seconds"] else [None] * 5
            test = t["test"] or {}
            short = [test[str(d)]["acc_total"] for d in SHORT if str(d) in test]
            rows.append([s, a, r, t["attempt"] or 1, " ".join(map(str, built)), " ".join(map(str, skipped)),
                         e["round_skipped"], t["attempt"] == 1 and r in div, e["n_raw_examples"],
                         e["n_effective_examples"], e["num_updates"], *secs, min(short) if short else None])
    return rows


def csv_text(header: list[str], rows: list[list]) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(header)
    for r in rows:
        w.writerow([_cell(x) for x in r])
    return buf.getvalue()


