def seed_models(reg: LadReg) -> None:
    lows = []
    for s in SEEDS:
        ev = [json.loads(x) for x in (lr.RUNS / f"ladder_s{s}_seed" / "log.jsonl").read_text().splitlines()]
        easy = [e for e in ev if e.get("event") == "eval" and e.get("set") == "easy"][-1]
