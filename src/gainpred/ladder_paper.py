"""Numbers, tables, figures and data files for the paper from the ladder's logs (task 4).

Run: ``uv run python -m gainpred.ladder_paper``. It reads only the fetched logs
(``results/ladder/runs/*``, ``results/ladder/training/*``, ``results/ladder/launches.jsonl``) and the
ladder test set's manifest, and writes:

* ``results/ladder/per_length.csv``: one row per ``check`` event (arm run x length reached);
* ``results/ladder/per_round.csv``: one row per attempt of every round with a ``round_done``;
* ``paper/generated/numbers_ladder.tex`` (macros ``\\gpLad...``) and ``results/ladder/macros.md``
  (each macro, its value and its meaning);
* ``paper/generated/table_ladder_lengths.tex`` and ``table_ladder_cuts.tex``;
* ``paper/generated/figure_ladder_accuracy.pdf`` and ``figure_ladder_loss.pdf``, with PNG copies in
  ``results/ladder/figures/``.

Words (as in the task)
======================
* The **counting test** of a round is the redo's test if the round was redone, otherwise the only
  one (``ladder_report.counting_tests``).
* **Final accuracy** at a length: ``acc_total`` in the counting test of the arm's last round.
* **Accuracy after its round**: ``acc_total`` in the counting test of the round that added the
  length (round r adds 2r + 6 and 2r + 7).

How a redone round's attempts are found
=======================================
Seed 5, arm 3 has two kinds of redo. Round 8 was redone by a second call (the continuation), so it
has two ``round_done`` events: the original call's (attempt 1) and the continuation's (attempt 2,
``continuation: true``). Round 14 was redone inside one call, so it has one ``round_done`` with
``redone: true`` whose seconds cover both attempts and whose ``num_updates`` is one attempt's.
"""

