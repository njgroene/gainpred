"""The paper test (P9): every teacher run with a perfect calculator in place of the model.

Usage::

    uv run python -m gainpred.paper_test             # 10,000 problems per size -> results/paper_test.md

What it shows
=============
With a perfect calculator every piece answer is right, so any wrong *built*
answer comes from the cutting itself: a carry crossing a cut. This isolates
what each teacher does to the problems, independent of any model:

* **kept** -- share of hard problems the teacher keeps an answer for.
* **right** -- share of kept answers that are actually right.
* **draws per kept** -- 1 / kept: how many candidates must be drawn per kept
  answer (P3 caps this at 20).
* **check 3** -- share of kept answers identical to one of the piece answers
  the teacher asked for (P8; added after the confirming runs, amendment 22).
  Expected 0% for the three split-and-combine teachers and 100% for sample and
  vote (``gainpred.check3``).

Expected, if the code matches the protocol:

* the no-carry rule: kept = share with no carry across cut 1 (~half for 2-piece
  cuts, ~a quarter for 3-piece), right = 100%;
* the agreement rule: right = 100%; draws per kept about 3 up to 12 digits and
  about 14 at 15 digits (P3);
* no selection: kept = 100%, right = share with no carry across cut 1;
* sample and vote: kept = right = 100% (a perfect calculator answers directly).

It is also the acceptance test "Cutting and combining" of P9. The output
compares the rule errors with Table 7 of Shin et al. (unfiltered labels up to
9 digits: 60.8% wrong even with every block sum right).
"""

from __future__ import annotations

import argparse
import random
from pathlib import Path

from gainpred.cuts import ADDITION_CUTS, HARD_DIGITS
from gainpred.data import draw_hard
from gainpred.formats import Addition, solve
from gainpred.check3 import check_3_addition, teacher_with_pieces
from gainpred.checks import confirmed_share
from gainpred.teachers import TEACHER_NAMES, TEACHERS, PerfectCalculator, build_all, cuts_of

SEED = 3001  # its own seed: these problems are never trained or tested on
OUT = Path("results/paper_test.md")


def draw(digits: int, n: int, seed: int = SEED) -> list[Addition]:
    rng = random.Random(seed * 100 + digits)
    return [draw_hard(rng, digits) for _ in range(n)]


def paper_test(n: int = 10_000, seed: int = SEED) -> dict[str, dict[int, dict[str, float]]]:
    """{teacher: {digits: {"kept": share, "right": share of kept, "confirmed": check 2b, "check_3": check 3}}}"""
    calculator = PerfectCalculator()
    table: dict[str, dict[int, dict[str, float]]] = {name: {} for name in TEACHERS}
    for digits in HARD_DIGITS:
        problems = draw(digits, n, seed)
        built = build_all(problems, [cuts_of(p) for p in problems], calculator)
        for name, teacher in TEACHERS.items():
            decisions = teacher(problems, calculator)
            kept = [d for d in decisions if d.kept is not None]
            right = sum(d.kept == solve(d.problem) for d in kept)
            table[name][digits] = {"kept": len(kept) / n, "right": right / len(kept) if kept else 0.0,
                                   "confirmed": confirmed_share(decisions, built) or 0.0,
                                   "check_3": check_3_addition(teacher_with_pieces(name, problems, calculator))}
    return table


def to_markdown(table: dict[str, dict[int, dict[str, float]]], n: int) -> str:
    sizes = list(HARD_DIGITS)
    lines = [
        "# Paper test: teachers with a perfect calculator",
        "",
        f"Generated by `uv run python -m gainpred.paper_test` ({n:,} random hard problems per size, seed {SEED}).",
        "Every piece is added correctly, so wrong built answers come only from carries crossing a cut.",
        "Percentages: **kept** = share of problems with a kept answer; **right** = share of kept answers that are right;",
        "**2b** = check 2b, share of kept answers confirmed by another cut (P8); **draws** = problems drawn per kept",
        "answer (P3 caps this at 20); **check 3** = share of kept answers identical to a piece answer the teacher",
        "asked for (P8; added after the confirming runs, amendment 22).",
        "",
        "| Teacher | | " + " | ".join(f"{d} ({'∣'.join(map(str, ADDITION_CUTS[d][0]))})" for d in sizes) + " |",
        "| --- | --- | " + " | ".join("---" for _ in sizes) + " |",
    ]
    for name, by_size in table.items():
        lines.append(f"| {TEACHER_NAMES[name].capitalize()} | kept | " + " | ".join(f"{100 * by_size[d]['kept']:.1f}" for d in sizes) + " |")
        lines.append("| | right | " + " | ".join(f"{100 * by_size[d]['right']:.1f}" for d in sizes) + " |")
        lines.append("| | 2b | " + " | ".join(f"{100 * by_size[d]['confirmed']:.1f}" for d in sizes) + " |")
        lines.append("| | draws | " + " | ".join(
            f"{1 / by_size[d]['kept']:.1f}" if by_size[d]["kept"] else "–" for d in sizes) + " |")
        lines.append("| | check 3 | " + " | ".join(
            "–" if by_size[d].get("check_3") is None else f"{100 * by_size[d]['check_3']:.1f}" for d in sizes) + " |")
    lines += ["", "Column headings give the size and its cut 1 (P4).", ""]
    if 8 in table["no_selection"] and 9 in table["no_selection"]:
        ours = 100 * (1 - (table["no_selection"][8]["right"] + table["no_selection"][9]["right"]) / 2)
        lines += [
            "## Comparison with Shin et al. (2026), Table 7",
            "",
            "Their Table 7 audits the kept labels of one round against the true answers. \"Rule errors\" is the share",
            "of labels that would be wrong even with every block sum right: our *no selection, 100 - right*.",
            "",
            "| | Shin et al. | Ours (cut 1) |",
            "| --- | --- | --- |",
            f"| Unfiltered, up to 9 digits: rule errors | 60.8 | {ours:.1f} (mean of 8 and 9 digits) |",
            "| Unfiltered, up to 23 digits: rule errors | 83.3 | not comparable (we stop at 15 digits; their block widths are not stated) |",
            f"| Filtered: rule errors | 0.0 | {100 - 100 * min(table['no_carry'][d]['right'] for d in sizes):.1f} |",
            "",
            "Their wrong labels with the filter (0.1–2.4%) come from wrong block sums by the model, which a perfect",
            "calculator cannot show. The agreement rule, sample and vote and the draws per kept answer are ours (P3, P5).",
        ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("-n", type=int, default=10_000, help="problems per size")
    args = parser.parse_args()
    markdown = to_markdown(paper_test(args.n), args.n)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(markdown)
    print(markdown)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
